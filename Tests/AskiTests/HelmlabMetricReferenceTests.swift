    @Test func euclideanDistanceIsMonotonicAndSymmetric() {
        let near = HelmlabMetric.xyzToHelmlabMetric(ColorConversion.linearSRGBToXYZ(SIMD3(0.5, 0.5, 0.5)))
        let mid = HelmlabMetric.xyzToHelmlabMetric(ColorConversion.linearSRGBToXYZ(SIMD3(0.6, 0.5, 0.5)))
        let far = HelmlabMetric.xyzToHelmlabMetric(ColorConversion.linearSRGBToXYZ(SIMD3(1.0, 0.0, 0.0)))
        let dNear = HelmlabMetric.euclideanDistance(near, mid)
        let dFar = HelmlabMetric.euclideanDistance(near, far)
        #expect(dFar > dNear, "Euclidean must keep ranking distant pairs")
        #expect(
            abs(
                HelmlabMetric.euclideanDistance(near, far)
                    - HelmlabMetric.euclideanDistance(far, near)) < 1e-12, "symmetric")
    }
