    // MARK: - Task 1: linear RGB → XYZ(D65) helpers

    @Test func linearSRGBWhiteMapsToD65WhitePoint() {
        let xyz = ColorConversion.linearSRGBToXYZ(SIMD3<Double>(1, 1, 1))
        #expect(abs(xyz.x - 0.95046) < 1e-4, "X")
        #expect(abs(xyz.y - 1.00000) < 1e-4, "Y")
        #expect(abs(xyz.z - 1.08906) < 1e-4, "Z")
    }

    @Test func linearSRGBRedMapsToFirstColumn() {
        let xyz = ColorConversion.linearSRGBToXYZ(SIMD3<Double>(1, 0, 0))
        #expect(abs(xyz.x - 0.41239079926595934) < 1e-9, "X")
        #expect(abs(xyz.y - 0.21263900587151027) < 1e-9, "Y")
        #expect(abs(xyz.z - 0.01933081871559182) < 1e-9, "Z")
    }

    @Test func linearP3AndSRGBWhitesShareTheSameXYZ() {
        let sRGBWhite = ColorConversion.linearSRGBToXYZ(SIMD3<Double>(1, 1, 1))
        let p3White = ColorConversion.linearP3ToXYZ(SIMD3<Double>(1, 1, 1))
        #expect(simd_length(sRGBWhite - p3White) < 1e-4)
    }

    // MARK: - Task 3: forward reference vectors
    //
    // Values pinned from helmlab 0.14.0 (v21) via /tmp/gen_helmlab_refs.py:
    // `MetricSpace().from_XYZ(M·rgb)` with inputs treated as LINEAR sRGB
    // (xyz = M·rgb, no gamma decode) so they match `linearSRGBToXYZ` across the
    // whole grid. Forward contract is ≥3 decimals (the bar the official JS port
    // met); the Double-vs-Double port actually agrees to ~1e-15 (see commit
    // 1d87313 / the eval research note).

    @Test func materialPrimariesMatchPinnedReferenceToThreeDecimals() {
        // (name, linear-RGB primary, expected MetricSpace-Lab). PINNED.
        let cases: [(name: String, rgb: SIMD3<Double>, expected: SIMD3<Double>)] = [
            ("red", SIMD3(1.0, 0.0, 0.0), SIMD3(0.9206916562124049, 0.9408189647112438, -0.20629920575074445)),
            ("green", SIMD3(0.0, 1.0, 0.0), SIMD3(0.740581076467783, -0.15477356824909633, 0.8916609181063444)),
            ("blue", SIMD3(0.0, 0.0, 1.0), SIMD3(0.7623634506187905, -0.1254051084078385, -0.20261328747520552)),
            ("white", SIMD3(1.0, 1.0, 1.0), SIMD3(1.1211211993998123, 0.10156484218807459, 0.20032415965717804)),
            ("black", SIMD3(0.0, 0.0, 0.0), SIMD3(0.0, 0.0, 0.0)),
            ("gray50", SIMD3(0.5, 0.5, 0.5), SIMD3(0.9748939394405974, 0.17389862804893247, 0.2058703039800843)),
            ("orange", SIMD3(1.0, 0.5, 0.0), SIMD3(0.9676686254009857, 0.5844992965047099, 0.8101573586436106)),
            ("cyan", SIMD3(0.0, 1.0, 1.0), SIMD3(0.8824490947607301, -0.16708698991974946, 0.22448604262150712)),
            ("magenta", SIMD3(1.0, 0.0, 1.0), SIMD3(1.3271449910319406, 0.09455128618912392, -0.0781003398901362)),
        ]
        for c in cases {
            let xyz = ColorConversion.linearSRGBToXYZ(c.rgb)
            let lab = HelmlabMetric.xyzToHelmlabMetric(xyz)
            #expect(abs(lab.x - c.expected.x) < 1e-3, "\(c.name) L")
            #expect(abs(lab.y - c.expected.y) < 1e-3, "\(c.name) a")
            #expect(abs(lab.z - c.expected.z) < 1e-3, "\(c.name) b")
        }
    }

